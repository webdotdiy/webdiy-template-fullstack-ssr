import { NeonPostgrestClient } from '@neondatabase/postgrest-js';
import { getAuthToken } from './neon-auth';

/*
 * Data API client: PostgREST over the project's Neon database, used in the
 * browser as the signed-in user. Everything you need is here; there is no
 * need to read the packages in node_modules.
 *
 *   const db = createDataClient();
 *   const { data, error } = await db.from('todos').select('*').order('created_at', { ascending: false });
 *   await db.from('todos').insert({ title }).select().single();
 *   await db.from('todos').update({ done: true }).eq('id', id);
 *   await db.from('todos').delete().eq('id', id);
 *   // A query doesn't throw on a database error: check `error` (error.message).
 *
 * Call it in an effect, an event handler or a clientLoader (TanStack Query
 * works well), never in a loader or a component's render: the user's token
 * exists only in the browser. Make it inside the function that queries, never
 * where a module loads: it throws until the database is turned on, and a
 * module that throws as it loads takes every page of the app down.
 *
 * Who may do what is decided in the database, by grants and Row-Level Security
 * (RLS); there is no other permission layer:
 *   - Every request carries the signed-in user's token and runs as the
 *     `authenticated` role, which already has SELECT, INSERT, UPDATE and DELETE
 *     on every table in `public`, tables a later migration adds included. A
 *     migration needs no GRANT for a table. Give a table's id
 *     `uuid default gen_random_uuid()` or `generated by default as identity`:
 *     a `serial` column's sequence is not covered, and inserts through the
 *     Data API would need `grant usage on sequence <table>_<column>_seq to
 *     authenticated` in its migration.
 *   - So RLS is the guard: turn it on for every table, with its policies, in
 *     the migration that makes the table. `auth.user_id()` is the signed-in
 *     user's id (text; the same value as useAuthSession()'s data.user.id):
 *
 *       create table todos (
 *         id uuid primary key default gen_random_uuid(),
 *         user_id text not null default auth.user_id(),
 *         title text not null,
 *         done boolean not null default false,
 *         created_at timestamptz not null default now()
 *       );
 *       alter table todos enable row level security;
 *       create policy own_todos on todos to authenticated
 *         using (user_id = auth.user_id()) with check (user_id = auth.user_id());
 *
 *   - Signed out there is no token. A page signed-out visitors and crawlers
 *     must read (public content) gets its data in its route's `loader`, on
 *     the server, through `DATABASE_URL` (the app's own role `app_rw`; see
 *     src/server/routes/example-server-write.ts for the policy it needs):
 *
 *       import { env } from 'cloudflare:workers';
 *       import { neon } from '@neondatabase/serverless';
 *       import { requireEnv } from '@/server/env';
 *
 *       export async function loader() {
 *         const sql = neon(requireEnv(env, 'DATABASE_URL'));
 *         return { tasks: await sql`select id, title from tasks order by title limit 50` };
 *       }
 *
 *     In a route module a binding's value has no type: read it with
 *     `requireEnv(env, 'DATABASE_URL')`, which gives its text or throws an
 *     error that says how to fix it. Inside the loader, never where the
 *     module loads.
 */

/** The Data API client, as the signed-in user. Throws when the database is not turned on yet. */
export function createDataClient(): NeonPostgrestClient {
  const dataApiUrl = import.meta.env.VITE_NEON_DATA_API_URL;

  if (!dataApiUrl) {
    throw new Error('The Neon database is not provisioned for this project yet.');
  }

  return new NeonPostgrestClient({
    dataApiUrl,
    options: {
      global: {
        fetch: async (input: RequestInfo | URL, init?: RequestInit) => {
          const token = await getAuthToken();
          const headers = new Headers(init?.headers);

          if (token) {
            headers.set('Authorization', `Bearer ${token}`);
          }

          return fetch(input, { ...init, headers });
        },
      },
    },
  });
}
